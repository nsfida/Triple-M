test("notifications are single lines that open a detail overlay with the related actions", () => {
  const js = text("Assets/app/messaging/01-messaging.js");
  assert.match(js, /list\.innerHTML = adminCommsState\.notifications\.map\(notificationRowHtml\)\.join\(""\);/);
  assert.match(js, /class="admin-comms-item notif-row/);
  assert.match(js, /openNotificationDetail\(n\);/);
  for (const action of ["live-accept", "live-decline", "review-payment", "open-user", "open"]) {
    assert.ok(js.includes(`"${action}"`), `detail action ${action}`);
  }
  assert.match(js, /role="dialog" aria-modal="true" aria-labelledby="notificationDetailTitle"/);
  assert.match(js, /e\.key === "Escape" && !modal\.classList\.contains\("hide"\)/);
  // All text is escaped before it is placed in the overlay.
  assert.match(js, /<dd dir="auto">\$\{escapeHtml\(val\)\}<\/dd>/);
  const css = text("Assets/style/57-notifications-messaging.css");
  assert.match(css, /\.notif-row-text\{[^}]*white-space:nowrap/);
  assert.match(css, /\.notification-detail-dialog\{/);
});

