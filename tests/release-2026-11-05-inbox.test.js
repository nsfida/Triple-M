"use strict";

/* 2026-11-05: Aziz knowledge base, one-place notifications, notification detail
 * overlay, Messages "Read all", conversation readability and CSS de-duplication. */
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");

const root = path.resolve(__dirname, "..");
const has = rel => fs.existsSync(path.join(root, rel));
const text = rel => fs.readFileSync(path.join(root, rel), "utf8");
const AZIZ = "supabase/functions/aziz-live-support";
const skipAziz = has(`${AZIZ}/index.ts`) ? false : "Aziz Edge Function source not present in this checkout";

test("Aziz knowledge base is generated from the public guides and is current", { skip: skipAziz }, () => {
  const r = spawnSync(process.execPath, ["scripts/build_aziz_knowledge.js", "--check"], { cwd: root, encoding: "utf8" });
  assert.equal(r.status, 0, r.stdout + r.stderr);
  const knowledge = text(`${AZIZ}/knowledge.ts`);
  assert.match(knowledge, /GENERATED by scripts\/build_aziz_knowledge\.js/);
  // No subscription prices (live prices come from the database) and no stale contact e-mail.
  assert.doesNotMatch(knowledge, /info@triplem\.vip/);
  assert.doesNotMatch(knowledge, /(?:pro monthly|pro yearly|per month|per year)[^.\n]{0,60}(?:\b(?:AED|SAR|USD|PKR|INR|EUR)\s?\d|\$\s?\d)/i);
  const sections = JSON.parse(knowledge.match(/AZIZ_KNOWLEDGE_SECTIONS[^=]*= (\[[\s\S]*?\]);\n/)[1]);
  assert.ok(sections.length > 100, "broad product coverage");
  for (const topic of ["Windows App", "Keyboard Shortcuts", "Excel to Triplem VIP", "Insurance Management", "Bank Reconciliation", "Month-End Close"]) {
    assert.ok(sections.some(s => s.title.includes(topic)), `knowledge covers ${topic}`);
  }
});

