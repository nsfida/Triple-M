#!/usr/bin/env node
"use strict";
/*
 * Builds supabase/functions/aziz-live-support/knowledge.ts from the maintained
 * public product references (llms-full.txt and the public SEO guides), so Aziz
 * answers from the same verified facts as the website and stays in sync when a
 * guide changes.
 *
 *   npm run aziz:knowledge          regenerate the file
 *   node scripts/build_aziz_knowledge.js --check   exit 1 if it is out of date
 *
 * Only public, non-sensitive product documentation is used. Prices are never
 * copied (Aziz receives live prices from the database), and contact details are
 * removed (Aziz has one authoritative contact block in its system prompt).
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const OUT = path.join(root, "supabase/functions/aziz-live-support/knowledge.ts");

// Order matters: the most frequently asked topics come first.
const SOURCES = [
  "llms-full.txt",
  "seo/faq.md",
  "seo/triplem.md",
  "seo/expense-tracking.md",
  "seo/account-details.md",
  "seo/inventory-management.md",
  "seo/loan-management.md",
  "seo/installment-plans.md",
  "seo/asset-management.md",
  "seo/insurance-management.md",
  "seo/notes-management.md",
  "seo/bitcoin-wallet.md",
  "seo/accounting-erp.md",
  "seo/accounting-setup.md",
  "seo/chart-of-accounts.md",
  "seo/accounts-receivable-payable.md",
  "seo/bank-reconciliation.md",
  "seo/vat-accounting.md",
  "seo/financial-reports.md",
  "seo/financial-audit.md",
  "seo/financial-timeline.md",
  "seo/triplem-ai.md",
  "seo/multi-currency-accounting.md",
  "seo/month-end-close.md",
  "seo/excel-to-triplem-vip.md",
  "seo/keyboard-shortcuts.md",
  "seo/windows-desktop-app.md",
  "seo/security-and-support.md",
  "seo/privacy-policy.md"
];

// Navigation / cross-link / contact sections that add no product knowledge.
const DROP_SECTION = /^(explore the wider|continue (through|with)|editorial and regional|official triplem vip contact|related (public|guides|pages|references)|public (navigation|references)|practical authority|regional reference|international finance for india|international currency availability|follow the records|explore |next steps|continue$|guide library|worldwide availability)/i;
const DROP_LINE = /^(canonical page:|last reviewed:|maintained by:|email:|facebook:|tiktok:|whatsapp:|- https?:\/\/|https?:\/\/)/i;

function clean(markdown) {
  return markdown
    .replace(/\r/g, "")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, "")
    .replace(/\[([^\]]+)\]\((?:https?:\/\/|\/|mailto:)[^)]*\)/g, "$1")
    .replace(/<[^>]+>/g, "")
    .replace(/\binfo@triplem\.vip\b/g, "the official support channels")
    .replace(/[ \t]+/g, " ");
}

function sectionsOf(rel) {
  const raw = clean(fs.readFileSync(path.join(root, rel), "utf8"));
  const lines = raw.split("\n");
  const docTitle = (lines.find(l => /^# /.test(l)) || rel).replace(/^#\s*/, "").replace(/\s*\|.*$/, "").replace(/\s*—\s*Full Public Product Reference$/, " overview").trim();
  const out = [];
  let current = null;
  for (const line of lines) {
    if (/^# /.test(line) || /^>/.test(line)) continue;
    const h2 = line.match(/^##\s+(.*)$/);
    if (h2) {
      current = { title: h2[1].trim(), lines: [], drop: DROP_SECTION.test(h2[1].trim()) };
      out.push(current);
      continue;
    }
    if (!current) continue;
    const t = line.trim();
    if (!t || DROP_LINE.test(t)) { current.lines.push(""); continue; }
    current.lines.push(t.replace(/^###\s+/, "* ").replace(/^####\s+/, "* "));
  }
  return out
    .filter(s => !s.drop)
    .map(s => ({ title: `${docTitle} - ${s.title}`, text: s.lines.join("\n").replace(/\n{3,}/g, "\n\n").trim() }))
    .filter(s => s.text.split(/\s+/).length >= 8);
}

function build() {
  const seen = new Set();
  const sections = [];
  for (const rel of SOURCES) {
    if (!fs.existsSync(path.join(root, rel))) continue;
    for (const s of sectionsOf(rel)) {
      const key = s.text.toLowerCase().replace(/\W+/g, " ").slice(0, 160);
      if (seen.has(key)) continue; // identical boilerplate repeated across guides
      seen.add(key);
      sections.push(s);
    }
  }
  // Worked accounting examples are fine; subscription prices are not.
  if (/(?:pro monthly|pro yearly|subscription|per month|per year|team seat)[^.\n]{0,60}(?:\b(?:AED|SAR|USD|PKR|INR|EUR)\s?\d|\$\s?\d)/i.test(sections.map(s => s.text).join("\n"))) {
    throw new Error("A public guide contains a price amount; Aziz must use live database prices only.");
  }
  const words = sections.reduce((n, s) => n + s.text.split(/\s+/).length, 0);
  const body = sections.map(s => `### ${s.title}\n${s.text}`).join("\n\n");
  return {
    words,
    count: sections.length,
    file: `// GENERATED by scripts/build_aziz_knowledge.js from the public product guides.
// Do not edit by hand: change the guide, then run \`npm run aziz:knowledge\`.
// ${sections.length} sections, ${words} words.

export const AZIZ_KNOWLEDGE_SECTIONS: ReadonlyArray<{ title: string; text: string }> = ${JSON.stringify(sections, null, 1)};

export const AZIZ_KNOWLEDGE = ${JSON.stringify(body)};
`
  };
}

const result = build();
if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== result.file) {
    console.error("Aziz knowledge is out of date. Run: npm run aziz:knowledge");
    process.exit(1);
  }
  console.log(`Aziz knowledge is current (${result.count} sections, ${result.words} words).`);
} else {
  fs.writeFileSync(OUT, result.file);
  console.log(`Wrote ${path.relative(root, OUT)}: ${result.count} sections, ${result.words} words.`);
}
